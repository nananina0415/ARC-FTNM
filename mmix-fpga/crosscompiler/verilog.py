from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

from . import builtins
from .model import CompileError
from .typesys import leaves


def module_name(spec):
    name = builtins.identifier(spec.name)
    if spec.arguments:
        # repr of immutable integer/type values contains no source location or object id.
        digest = hashlib.sha256(repr(spec.arguments).encode("utf-8")).hexdigest()
        name += "_args_" + digest
    return name


def module_path(spec):
    folder = ("builtin",) if spec.builtin else spec.name[:-1]
    return "/".join(folder + (module_name(spec) + ".v",))


def concatenate(expressions):
    if len(expressions) == 1:
        return expressions[0]
    return "{" + ", ".join(reversed(expressions)) + "}"


def generate(module):
    spec = module.spec
    ports = list(leaves(module.interface))
    name = module_name(spec)
    result = ["// Generated by crosscompiler 0.1.0. Do not edit.", "`default_nettype none", f"module {name} ("]
    for index, (path, port) in enumerate(ports):
        direction = {"in": "input", "out": "output", "inout": "inout"}[port.direction]
        comma = "," if index + 1 < len(ports) else ""
        result.append(f"    {direction} wire [{port.width - 1}:0] {builtins.identifier(('port',) + path)}{comma}")
    result.append(");")
    if spec.builtin:
        result.extend(builtins.body(spec))
    else:
        nets = module.nets
        canonical = {}
        # Prefer existing public nets: inout first, then input, then output.
        ranks = {"inout": 0, "in": 1, "out": 2}
        ordered = sorted(module.ports, key=lambda pin: (ranks[pin.direction], pin.path))
        for pin in ordered:
            port_name = builtins.identifier(("port",) + pin.path)
            for index, bit in enumerate(pin.bits):
                canonical.setdefault(nets.find(bit), f"{port_name}[{index}]")
        for bit in range(len(nets.parent)):
            root = nets.find(bit)
            if root not in canonical:
                canonical[root] = f"net_{root}"
                result.append(f"wire net_{root};")
        def vector(bits):
            return concatenate([canonical[nets.find(bit)] for bit in bits])
        for pin in ordered:
            port_name = builtins.identifier(("port",) + pin.path)
            for index, bit in enumerate(pin.bits):
                public, internal = f"{port_name}[{index}]", canonical[nets.find(bit)]
                if public == internal:
                    continue
                if pin.direction == "inout":
                    result.append(f"tran ({public}, {internal});")
                elif pin.direction == "in":
                    result.append(f"assign {internal} = {public};")
                else:
                    result.append(f"assign {public} = {internal};")
        for bits, value, _ in module.constants:
            from .elaborator import OPEN
            literal = f"{len(bits)}'bz" if value is OPEN else f"{len(bits)}'d{value}"
            result.append(f"assign {vector(bits)} = {literal};")
        symbols = {"and": " & ", "or": " | ", "xor": " ^ "}
        for gate in module.gates:
            expression = "~(" + vector(gate.inputs[0]) + ")" if gate.operation == "not" else (
                "(" + symbols[gate.operation].join(vector(bits) for bits in gate.inputs) + ")")
            result.append(f"assign {vector(gate.output)} = {expression};")
        for instance in module.instances:
            result.append(f"{module_name(instance.module.spec)} {builtins.identifier(('instance',) + instance.path)} (")
            for index, pin in enumerate(instance.pins):
                comma = "," if index + 1 < len(instance.pins) else ""
                result.append(f"    .{builtins.identifier(('port',) + pin.path)}({vector(pin.bits)}){comma}")
            result.append(");")
    result.extend(["endmodule", "`default_nettype wire", ""])
    return "\n".join(result)


def source_map(module):
    from .elaborator import OPEN
    def location(loc):
        return None if loc is None else {"file": loc.file, "line": loc.line, "column": loc.column}
    return {
        "module": module_name(module.spec), "file": module_path(module.spec),
        "source": location(module.location),
        "ports": [{"name": builtins.identifier(("port",) + path), "path": list(path),
                   "direction": port.direction, "width": port.width}
                  for path, port in leaves(module.interface)],
        "pins": [{"owner": pin.owner, "path": list(pin.path), "source": location(pin.location),
                  "nets": [module.nets.find(bit) for bit in pin.bits]} for pin in module.pins],
        "gates": [{"operation": gate.operation, "source": location(gate.location),
                   "nets": [module.nets.find(bit) for bit in gate.output]} for gate in module.gates],
        "constants": [{"value": "Z" if value is OPEN else value, "source": location(loc),
                       "nets": [module.nets.find(bit) for bit in bits]}
                      for bits, value, loc in module.constants],
        "instances": [{"path": list(instance.path), "module": module_name(instance.module.spec),
                       "source": location(instance.location)} for instance in module.instances],
    }


def external_sources(modules, out_dir):
    """Third-party Verilog that builtin primitives instantiate, as paths relative to out_dir."""
    root = Path(__file__).resolve().parent.parent
    found = []
    for module in modules:
        if module.spec.builtin:
            for relative in builtins.EXTERNAL_SOURCES.get(module.spec.name[-1], ()):
                path = root / relative
                if not path.is_file():
                    raise CompileError(f"{module.spec.name[-1]} needs {relative}; initialize the git submodule")
                entry = relative if out_dir is None else os.path.relpath(path, Path(out_dir).resolve())
                found.append(entry.replace("\\", "/"))
    return sorted(set(found))


def artifacts(modules, top, single_file=False, out_dir=None):
    ordered = sorted(modules, key=lambda module: module_path(module.spec))
    generated = {module_path(module.spec): generate(module) for module in ordered}
    if single_file:
        generated = {"design.v": "\n".join(generated.values())}
    files = sorted(generated)
    # Third-party files come last: generated modules restore `default_nettype wire`.
    generated["sources.f"] = "\n".join(files + external_sources(ordered, out_dir)) + "\n"
    generated["top.txt"] = module_name(top.spec) + "\n"
    mapping = {"format": 1, "top": module_name(top.spec), "single_file": single_file,
               "modules": [source_map(module) for module in ordered]}
    if single_file:
        for entry in mapping["modules"]:
            entry["file"] = "design.v"
    generated["source-map.json"] = json.dumps(mapping, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    return generated
