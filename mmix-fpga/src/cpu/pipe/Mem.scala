/*
 * LDB/LDBU $X,$Y,$Z|Z — 바이트 로드 (부호있음/부호없음)
 *   바이트 M[$Y+$Z](또는 $Y+Z)를 $X에 로드. LDB는 -128~127의 부호있는 수로,
 *   LDBU는 0~255의 부호없는 수로 해석.
 *
 * LDW/LDWU $X,$Y,$Z|Z — 와이드(2바이트) 로드
 *   주소의 최하위 1비트는 무시(2바이트 정렬). 부호있음/없음 구분은 LDB와 동일.
 *
 * LDT/LDTU $X,$Y,$Z|Z — 테트라(4바이트) 로드
 *   주소의 최하위 2비트는 무시(4바이트 정렬). 부호있음/없음 구분은 LDB와 동일.
 *
 * LDO/LDOU $X,$Y,$Z|Z — 옥타(8바이트) 로드
 *   주소의 최하위 3비트는 무시(8바이트 정렬). 옥타바이트는 부호 구분이 없으므로
 *   LDO와 LDOU는 동작이 완전히 동일(일관성을 위해 둘 다 존재).
 *
 * LDHT $X,$Y,$Z|Z — 상위 테트라 로드
 *   M4[$Y+$Z](또는 $Y+Z)를 $X의 상위 4바이트에 싣고 하위 4바이트는 0으로 클리어.
 *   테트라바이트 덧셈/뺄셈의 오버플로우를 빠르게 검출하는 용도로 쓰인다.
 *
 * LDUNC $X,$Y,$Z|Z — 캐시하지 않는 옥타 로드
 *   의미는 LDO와 동일하지만, 로드한 옥타바이트(및 인접 바이트들)를 가까운 미래에
 *   다시 읽거나 쓰지 않을 것이라는 힌트를 CPU에 전달(캐싱하지 않음).
 *
 * PRELD X,$Y,$Z|Z — 데이터 미리 읽기 힌트 (preload)
 *   레지스터나 메모리에 아무 영향도 주지 않는다. M[$Y+$Z](또는 $Y+Z)부터
 *   X+1바이트가 가까운 미래에 로드되거나 저장될 것이라는 힌트만 전달.
 *
 * PREGO X,$Y,$Z|Z — 명령어 미리 읽기 힌트 (prefetch to go)
 *   PRELD와 동일하나, 해당 범위가 곧 "명령어로서" 사용될 것이라는 힌트.
 *
 * STB/STBU $X,$Y,$Z|Z — 바이트 저장 (부호있음/부호없음)
 *   $X의 최하위 1바이트를 M[$Y+$Z](또는 $Y+Z)에 저장. STB는 $X가 -128~127을
 *   벗어나면 오버플로우 예외, STBU는 검사 없음.
 *
 * STW/STWU, STT/STTU, STO/STOU $X,$Y,$Z|Z — 와이드/테트라/옥타 저장
 *   각각 2/4/8바이트 저장. 부호있는 버전(STW/STT)은 값이 해당 폭의 부호있는
 *   범위를 벗어나면 오버플로우 예외, 부호없는 버전(*U)은 검사 없음.
 *   STO와 STOU는 완전히 동일(옥타는 부호 구분 없음).
 *
 * STHT $X,$Y,$Z|Z — 상위 테트라 저장
 *   $X의 상위 4바이트를 M4[$Y+$Z](또는 $Y+Z)에 저장.
 *
 * STCO X,$Y,$Z|Z — 상수 옥타 저장 (store constant octabyte)
 *   레지스터가 아닌 부호없는 즉치 바이트 X 자체를 8바이트로 확장해
 *   M8[$Y+$Z](또는 $Y+Z)에 저장.
 *
 * STUNC $X,$Y,$Z|Z — 캐시하지 않는 옥타 저장
 *   의미는 STO와 동일하지만 캐싱하지 않는다는 힌트를 CPU에 전달.
 *
 * SYNCD $X,$Y,$Z|Z — 데이터 동기화
 *   쓰기버퍼나 라이트백 데이터캐시가 없으면 레지스터/메모리에 아무 효과도 없다.
 *   있으면, M[$Y+$Z](또는 $Y+Z)부터 X+1바이트가 실제로 메모리에 반영되도록 강제한다
 *   (캐시에만 있고 아직 안 쓰인 이전 STORE 결과를 내보냄).
 *   음수 주소에서 실행하면 추가로 그 바이트들을 데이터캐시에서도 제거한다.
 *
 * PREST X,$Y,$Z|Z — 데이터 미리 저장 힌트 (prestore)
 *   데이터캐시가 있는 경우, M[$Y+$Z](또는 $Y+Z)부터 X+1바이트 전부를
 *   곧 store할 것이므로 기존 내용을 무시(로드 없이 캐시라인만 확보)해도
 *   된다는 힌트. 캐시가 없으면 아무 효과 없음.
 *
 * SAVE $X,0 — 프로세스 상태 저장
 *   현재 로컬/글로벌 레지스터와 rB/rD/rE/rH/rJ/rM/rR/rP/rW/rX/rY/rZ 등
 *   특수 레지스터들을 레지스터 스택에 밀어넣고, L을 0으로 리셋.
 *   저장된 최상단 옥타바이트의 주소를 전역 레지스터 $X에 저장. 인터럽트 가능.
 *
 * UNSAVE 0,$Z — 프로세스 상태 복원
 *   SAVE가 반환했던 주소($Z)로부터 모든 레지스터를 복원. 인터럽트 가능.
 *   파괴적 연산이므로 같은 컨텍스트를 두 번 UNSAVE할 수 없다.
*/

package cpu

import chisel3._
import chisel3.util._

case class MemOp() extends Bundle {
  val flag = UInt(6.W)
  val x    = UInt(8.W)
  val y    = UInt(8.W)
  val z    = UInt(8.W)
}

class Mem extends Module {
  val io = IO(new Bundle {
    val op  = Flipped(Valid(MemOp()))
    val acc = Output(UInt(64.W))
  })

  io.acc := 0.U
}
